    methods (Static)
        function result = baselineDemo(choice)
            arguments
                choice (1,1) string {mustBeMember(choice,["Housing prices","Sample fit challenge","Ventilator practice"])}
            end

            data = TeachingModuleShowcaseSupportRegressionBasics.makeBaselineScenario(choice);
            mdl = fitlm(data.x,data.y);

            xGrid = linspace(min(data.x),max(data.x),200)';
            fitGrid = predict(mdl,xGrid);
            fittedValues = predict(mdl,data.x);
            residuals = data.y - fittedValues;
            sse = sum(residuals.^2);

            summary = table( ...
                data.Label,sse,mdl.Coefficients.Estimate(2),mdl.Coefficients.Estimate(1), ...
                'VariableNames',["Scenario","SSE","Slope","Intercept"]);

            result = struct( ...
                "Label",data.Label, ...
                "x",data.x, ...
                "y",data.y, ...
                "xGrid",xGrid, ...
                "FitGrid",fitGrid, ...
                "FittedValues",fittedValues, ...
                "Residuals",residuals, ...
                "SSE",sse, ...
                "XLabel",data.XLabel, ...
                "YLabel",data.YLabel, ...
                "Summary",summary, ...
                "TeachingNote",data.TeachingNote);
        end

        function result = linearityAssumptionDemo(choice)
            arguments
                choice (1,1) string {mustBeMember(choice,["House prices with amenities","Heat exchanger soft sensor","DC power practice"])}
            end

            data = TeachingModuleShowcaseSupportRegressionBasics.makeMultipleScenario(choice);
            [X,~] = TeachingModuleShowcaseSupportRegressionBasics.fullPredictorMatrix(data);

            mdl1 = fitlm(data.x1,data.y);
            mdl2 = fitlm(data.x2,data.y);
            fullMdl = fitlm(X,data.y);

            x1Grid = linspace(min(data.x1),max(data.x1),200)';
            x2Grid = linspace(min(data.x2),max(data.x2),200)';
            y1Fit = predict(mdl1,x1Grid);
            y2Fit = predict(mdl2,x2Grid);
            fittedValues = predict(fullMdl,X);
            residuals = data.y - fittedValues;

            summary = table( ...
                [data.Predictor1Name; data.Predictor2Name; "Full model"], ...
                ["Simple R-squared"; "Simple R-squared"; "Adjusted R-squared"], ...
                [mdl1.Rsquared.Ordinary; mdl2.Rsquared.Ordinary; fullMdl.Rsquared.Adjusted], ...
                ["Look for an approximately straight trend, not a pronounced curve."; "Look for an approximately straight trend, not a pronounced curve."; "Residuals should stay near zero with no curve, drift, clustering, or fan shape."], ...
                'VariableNames',["Diagnostic view","Metric","Value","What to look for"]);

            if isfield(data,"x3")
                displayNote = "The compact preview plots the first two predictors, while the full-model check is computed from the model that also includes " + data.Predictor3Name + ". Treat the scatter plots as a first screen: if the full-model residuals still show structure, revise the model before interpreting the coefficients.";
            else
                displayNote = "The scatter plots are a first screen, and the compact full-model check helps you decide whether the linear form still looks reasonable. If that check curves, drifts, clusters, or fans out, treat the model as provisional and revisit the model form.";
            end

            result = struct( ...
                "Label",data.Label, ...
                "x1",data.x1, ...
                "x2",data.x2, ...
                "y",data.y, ...
                "x1Grid",x1Grid, ...
                "x2Grid",x2Grid, ...
                "Y1Fit",y1Fit, ...
                "Y2Fit",y2Fit, ...
                "FittedValues",fittedValues, ...
                "Residuals",residuals, ...
                "X1Label",data.X1Label, ...
                "X2Label",data.X2Label, ...
                "YLabel",data.YLabel, ...
                "Summary",summary, ...
                "DisplayNote",displayNote, ...
                "TeachingNote",data.LinearityNote);
        end

        function result = multipleRegressionDemo(choice)
            arguments
                choice (1,1) string {mustBeMember(choice,["House prices with amenities","Heat exchanger soft sensor","DC power practice"])}
            end

            data = TeachingModuleShowcaseSupportRegressionBasics.makeMultipleScenario(choice);
            [X,predictorNames] = TeachingModuleShowcaseSupportRegressionBasics.fullPredictorMatrix(data);
            mdl = fitlm(X,data.y);

            fittedValues = predict(mdl,X);
            residuals = data.y - fittedValues;

            x1Grid = linspace(min(data.x1),max(data.x1),24);
            x2Grid = linspace(min(data.x2),max(data.x2),24);
            [X1Grid,X2Grid] = meshgrid(x1Grid,x2Grid);

            if isfield(data,"x3")
                heldValue = mean(data.x3);
                surfaceInput = [X1Grid(:) X2Grid(:) repmat(heldValue,numel(X1Grid),1)];
                surfaceNote = "Surface preview holds " + data.Predictor3Name + " at its mean value so you can read what the model predicts on the plane without losing the full-model fit.";
            else
                surfaceInput = [X1Grid(:) X2Grid(:)];
                surfaceNote = "Surface preview uses both predictors directly so you can compare the fitted plane to the data cloud before moving to the interactive app.";
            end

            surfaceFit = reshape(predict(mdl,surfaceInput),size(X1Grid));
            modelRMSE = mdl.RMSE;
            summary = table( ...
                data.Label,size(X,2),modelRMSE,mdl.Rsquared.Adjusted, ...
                'VariableNames',["Scenario","Number of predictors","Model RMSE","Adjusted R-squared"]);

            coefficientTable = table( ...
                ["(Intercept)"; predictorNames], ...
                mdl.Coefficients.Estimate, ...
                'VariableNames',["Coefficient","Estimate"]);

            result = struct( ...
                "Label",data.Label, ...
                "x1",data.x1, ...
                "x2",data.x2, ...
                "y",data.y, ...
                "X1Grid",X1Grid, ...
                "X2Grid",X2Grid, ...
                "SurfaceFit",surfaceFit, ...
                "FittedValues",fittedValues, ...
                "Residuals",residuals, ...
                "X1Label",data.X1Label, ...
                "X2Label",data.X2Label, ...
                "YLabel",data.YLabel, ...
                "Summary",summary, ...
                "CoefficientTable",coefficientTable, ...
                "ANOVATable",anova(mdl,"summary"), ...
                "SurfaceNote",surfaceNote, ...
                "TeachingNote",data.TeachingNote);
        end

