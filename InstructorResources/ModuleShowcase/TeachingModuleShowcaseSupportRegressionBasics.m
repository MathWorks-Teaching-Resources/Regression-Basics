    projectRoot = fileparts(fileparts(mfilename("fullpath")));
    dataFile = fullfile(projectRoot,"Data","MultivariateData.mat");
    S = load(dataFile,"x1","x2","y");
    x1 = S.x1;
    x2 = S.x2;
    y = S.y;
catch
    rng(42,"twister")
