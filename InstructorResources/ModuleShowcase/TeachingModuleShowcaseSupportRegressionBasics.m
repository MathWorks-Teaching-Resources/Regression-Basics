        function result = curvilinearDemo(choice)
            arguments
                choice (1,1) string {mustBeMember(choice,["Crop yield and salinity","Battery lifetime decay","Bioreactor temperature"])}
            end

            scenario = TeachingModuleShowcaseSupportRegressionBasics.makeCurvilinearScenario(choice);
            x = scenario.x;
            y = scenario.y;
            xGrid = linspace(min(x),max(x),300)';

            switch scenario.Kind
                case "crop"
                    modelNames = ["Linear"; "Quadratic polynomial"; "Power law (linearized)"];
                    fitData = zeros(numel(x),3);
                    fitGrid = zeros(numel(xGrid),3);
                    teachingRead = [ ...
                        "Start on standard axes and ask whether a straight line is already adequate."; ...
                        "Compare the polynomial fit on standard axes and see whether it captures the visible curvature."; ...
                        "Use log-log axes, where both axes are logarithmic, to test whether a power law becomes straight enough to justify."];

                    linearCoeffs = polyfit(x,y,1);
                    quadCoeffs = polyfit(x,y,2);
                    mask = (x > 0) & (y > 0);
                    powerCoeffs = polyfit(log10(x(mask)),log10(y(mask)),1);
                    powerA = 10.^powerCoeffs(2);
                    powerB = powerCoeffs(1);

                    fitData(:,1) = polyval(linearCoeffs,x);
                    fitGrid(:,1) = polyval(linearCoeffs,xGrid);
                    fitData(:,2) = polyval(quadCoeffs,x);
                    fitGrid(:,2) = polyval(quadCoeffs,xGrid);
                    fitData(:,3) = powerA * x.^powerB;
                    fitGrid(:,3) = powerA * xGrid.^powerB;

                    primaryView = struct( ...
                        "Mode","plot", ...
                        "Title","Standard axes: polynomial shape", ...
                        "FitX",xGrid, ...
                        "FitY",fitGrid(:,2), ...
                        "FitName","Quadratic polynomial", ...
                        "XAxisLabel",scenario.XLabel, ...
                        "YAxisLabel",scenario.YLabel);

                    positiveGrid = xGrid > 0;
                    secondaryView = struct( ...
                        "Mode","loglog", ...
                        "Title","Log-log axes: power-law check", ...
                        "FitX",xGrid(positiveGrid), ...
                        "FitY",fitGrid(positiveGrid,3), ...
                        "FitName","Power-law fit", ...
                        "XAxisLabel",scenario.XLabel, ...
                        "YAxisLabel",scenario.YLabel);

                    axisNote = "Start on ordinary axes, compare the fit errors, then use log-log axes, where both axes are logarithmic, to test whether a power-law model becomes straight enough to justify. Choose the simplest model that captures the important pattern and stays easy to interpret.";

                case "battery"
                    modelNames = ["Linear"; "Exponential (linearized)"];
                    fitData = zeros(numel(x),2);
                    fitGrid = zeros(numel(xGrid),2);
                    teachingRead = [ ...
                        "Start on standard axes and check whether a straight line is already adequate."; ...
                        "Use semilogy axes, where only the response axis is logarithmic, to test whether exponential decay gives a more believable model."];

                    linearCoeffs = polyfit(x,y,1);
                    mask = y > 0;
                    expoCoeffs = polyfit(x(mask),log(y(mask)),1);
                    expoA = exp(expoCoeffs(2));
                    expoB = expoCoeffs(1);

                    fitData(:,1) = polyval(linearCoeffs,x);
                    fitGrid(:,1) = polyval(linearCoeffs,xGrid);
                    fitData(:,2) = expoA * exp(expoB * x);
                    fitGrid(:,2) = expoA * exp(expoB * xGrid);

                    primaryView = struct( ...
                        "Mode","plot", ...
                        "Title","Standard axes: curved decay", ...
                        "FitX",xGrid, ...
                        "FitY",fitGrid(:,2), ...
                        "FitName","Exponential fit", ...
                        "XAxisLabel",scenario.XLabel, ...
                        "YAxisLabel",scenario.YLabel);

                    secondaryView = struct( ...
                        "Mode","semilogy", ...
                        "Title","Semilogy axes: exponential check", ...
                        "FitX",xGrid, ...
                        "FitY",fitGrid(:,2), ...
                        "FitName","Exponential fit", ...
                        "XAxisLabel",scenario.XLabel, ...
                        "YAxisLabel",scenario.YLabel);

                    axisNote = "The table compares linear and exponential candidates, and the semilogy view shows whether the transformed response becomes straight enough to justify an exponential model without adding unnecessary complexity.";

                otherwise
                    modelNames = ["Linear"; "Quadratic polynomial"; "Cubic polynomial"];
                    fitData = zeros(numel(x),3);
                    fitGrid = zeros(numel(xGrid),3);
                    teachingRead = [ ...
                        "Start on standard axes and check whether a straight line is already adequate."; ...
                        "Use a quadratic fit on standard axes and see whether it captures the main bend."; ...
                        "Check a higher-order polynomial only if it adds visible structure you can still explain."];

                    poly1 = polyfit(x,y,1);
                    poly2 = polyfit(x,y,2);
                    poly3 = polyfit(x,y,3);

                    fitData(:,1) = polyval(poly1,x);
                    fitGrid(:,1) = polyval(poly1,xGrid);
                    fitData(:,2) = polyval(poly2,x);
                    fitGrid(:,2) = polyval(poly2,xGrid);
                    fitData(:,3) = polyval(poly3,x);
                    fitGrid(:,3) = polyval(poly3,xGrid);

                    primaryView = struct( ...
                        "Mode","plot", ...
                        "Title","Standard axes: polynomial behavior", ...
                        "FitX",xGrid, ...
                        "FitY",fitGrid(:,2), ...
                        "FitName","Quadratic polynomial", ...
                        "XAxisLabel",scenario.XLabel, ...
                        "YAxisLabel",scenario.YLabel);

                    secondaryView = struct( ...
                        "Mode","semilogy", ...
                        "Title","Semilogy check: still curved", ...
                        "FitX",xGrid, ...
                        "FitY",fitGrid(:,2), ...
                        "FitName","Quadratic polynomial", ...
                        "XAxisLabel",scenario.XLabel, ...
                        "YAxisLabel",scenario.YLabel);

                    axisNote = "Different axes are still worth checking, but this scenario stays most interpretable on standard axes with a polynomial fit, so prefer the polynomial model unless a transformed view becomes clearly straighter and easier to explain.";
            end

            rmse = zeros(numel(modelNames),1);
            for idx = 1:numel(modelNames)
                rmse(idx) = sqrt(mean((fitData(:,idx) - y).^2));
            end

            modelNamesCol = modelNames(:);
            teachingReadCol = teachingRead(1:numel(modelNames));
            teachingReadCol = teachingReadCol(:);
            summary = table(modelNamesCol,rmse(:),teachingReadCol,'VariableNames',["Model","RMSE","What to notice"]);
            [~,bestIdx] = min(rmse);

            result = struct( ...
                "Label",scenario.Label, ...
                "x",x, ...
                "y",y, ...
                "xGrid",xGrid, ...
                "FitGrid",fitGrid, ...
                "ModelNames",modelNames, ...
                "BestModel",modelNames(bestIdx), ...
                "Summary",summary, ...
                "PrimaryView",primaryView, ...
                "SecondaryView",secondaryView, ...
                "XLabel",scenario.XLabel, ...
                "YLabel",scenario.YLabel, ...
                "AxisNote",axisNote, ...
                "TeachingNote",scenario.TeachingNote);
        end

    end

