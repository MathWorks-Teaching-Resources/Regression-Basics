        function S = loadData(filename,variables)
            proj = currentProject;

            fullName = fullfile(proj.RootFolder,"Data",filename);

            if ~isfile(fullName)
                error("Could not find data file: %s",fullName)
            end

            vars = cellstr(variables);
            S = load(fullName,vars{:});
        end
        function [X,predictorNames] = fullPredictorMatrix(data)
            X = [data.x1 data.x2];
            predictorNames = [data.Predictor1Name; data.Predictor2Name];

            if isfield(data,"x3")
                X = [X data.x3];
                predictorNames(end+1,1) = data.Predictor3Name;
            end
        end

        function [mDot,dT,QkW] = makeHeatExchangerData()
            rng(11,"twister")
            n = 121;
            mDot = 1.30 + 0.22 * randn(n,1);
            dT = 20.0 + 2.60 * randn(n,1);
            mDot = max(0.8,min(mDot,1.9));
            dT = max(12,min(dT,28));
            QkW = 5 + 65 * mDot + 12 * dT + 0.9 * randn(n,1);
        end
