    x1 = 1 + 4*rand(n,1);
    x2 = 500 + 2000*rand(n,1);
    truea1 = 7500;
    truea2 = 250;
    truea0 = 6000;
    y = truea1*x1 + truea2*x2 + truea0 + 20000*randn(n,1);
end

X = [ones(length(x1),1),x1,x2];
